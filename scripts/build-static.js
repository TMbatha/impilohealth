'use strict';

/**
 * Tiny dependency-free CommonJS bundler: packs src/browser/entry.js and everything it
 * requires (domain, application, infrastructure) into web/shared/backend.js, which sets
 * globalThis.FXBackend. Run: npm run build:static
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const entry = path.join(root, 'src/browser/entry.js');
const out = path.join(root, 'web/shared/backend.js');

const modules = new Map(); // abs path -> { id, code, deps: {spec: id} }

function resolve(from, spec) {
  const base = path.resolve(path.dirname(from), spec);
  for (const c of [base, `${base}.js`, `${base}.json`, path.join(base, 'index.js')]) {
    if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  }
  throw new Error(`Cannot resolve '${spec}' from ${path.relative(root, from)}`);
}

function add(file) {
  if (modules.has(file)) return modules.get(file).id;
  const mod = { id: modules.size, code: '', deps: {} };
  modules.set(file, mod);
  const src = fs.readFileSync(file, 'utf8');
  if (file.endsWith('.json')) {
    mod.code = `module.exports = ${src.trim()};`;
    return mod.id;
  }
  mod.code = src;
  const codeOnly = src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  for (const [, spec] of codeOnly.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)) {
    if (!spec.startsWith('.')) throw new Error(`Non-relative require '${spec}' in ${path.relative(root, file)} cannot run in the browser`);
    mod.deps[spec] = add(resolve(file, spec));
  }
  return mod.id;
}

add(entry);

const defs = [...modules.entries()].map(([file, m]) => `  // ${path.relative(root, file).replace(/\\/g, '/')}
  ${m.id}: [function (module, exports, require) {
${m.code}
  }, ${JSON.stringify(m.deps)}]`).join(',\n');

const bundle = `/* GENERATED by scripts/build-static.js. Do not edit; run \`npm run build:static\`. */
(function () {
var defs = {
${defs}
};
var cache = {};
function load(id) {
  if (cache[id]) return cache[id].exports;
  var module = cache[id] = { exports: {} };
  var def = defs[id];
  def[0].call(module.exports, module, module.exports, function (spec) {
    if (!(spec in def[1])) throw new Error('Module not bundled: ' + spec);
    return load(def[1][spec]);
  });
  return module.exports;
}
globalThis.FXBackend = load(0);
})();
`;

fs.writeFileSync(out, bundle);
console.log(`Wrote ${path.relative(root, out)} (${modules.size} modules, ${(bundle.length / 1024).toFixed(1)} KB)`);
